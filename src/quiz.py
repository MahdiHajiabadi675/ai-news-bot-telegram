def pick(ordinal: int, used=()):
    """یک کوییز چرخشی که اخیراً استفاده نشده → (quiz، id)"""
    used = set(used or ())
    for i in range(len(QUIZ_BANK)):
        q = QUIZ_BANK[(ordinal + i) % len(QUIZ_BANK)]
        if q["id"] not in used:
            return q, q["id"]
    q = QUIZ_BANK[ordinal % len(QUIZ_BANK)]
    return q, q["id"]
