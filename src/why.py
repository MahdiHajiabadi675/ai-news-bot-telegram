_RUMOR = "هنوز رسمی نیست؛ تا تأیید، روی آن برنامه‌ریزی نکن و منتظر منبع اصلی بمان."

_MAX_LEN = 240


def why_it_matters(item) -> str:
    """یک جملهٔ کوتاه «چرا مهم است» یا رشتهٔ خالی."""
    if not SHOW_WHY_IT_MATTERS or not isinstance(item, dict):
        return ""
    if item.get("confidence") == "rumor":
        return _RUMOR
    text = _WHY.get(str(item.get("category") or ""), "")
    return text if len(text) <= _MAX_LEN else text[:_MAX_LEN - 1].rstrip() + "…"
